import type { PetLook } from "./pets.js"

/**
 * 登场。开应用、或者换一家引擎的时候，当前那只**不是「啪」地出现**。
 *
 * ## 为什么值得单开一层
 *
 * 「现在是哪一家在答」这件事，界面上已经有三处在说：输入框底下那颗下拉、
 * 亮着的那只、头顶那颗点。三处都是**静态**的——你得去看才知道，
 * 而换引擎恰恰是个**发生在某一刻**的事件，静态的东西说不了「刚才变了」。
 *
 * 出场是唯一一处按时间说话的：一团史莱姆砸在地上和一只螃蟹被伞吊下来，
 * 是两件事，不是两个色号。**它比配色更快，因为不需要先记住谁是什么颜色。**
 *
 * ## 四种登场按物性分，不是按好看分
 *
 * - **史莱姆砸下来**，落地摊成一滩再弹回原形。软体没有别的出场方式：
 *   它没有腿也没有翅膀，能自己发生的位移只有掉下来。
 * - **螃蟹是降落伞空投的**。蟹不会飞，所以它自己到不了空中——
 *   那就必须有个东西把它送下来，落地那刻伞脱钩飘走。
 * - **鲸先炸一圈水花再划弧跃出来**。它本来就在水面下，出场是「浮上来」。
 * - **没见过的那一家只是淡进来。** `pets.css` 里那句「不编花样」管到这儿：
 *   它连出场都不该有花样，而这个「没有」本身就是信号——
 *   台面上多了一只不认识的，你一眼就知道它是不认识的那一类。
 *
 * 纯逻辑：只回答「这只该用哪一种、播多久」，动画本身在 `pets.css`，
 * 什么时候播在 `usePetEntry.ts`。
 */
export type EntryKind = "drop" | "chute" | "splash" | "fade"

/**
 * 每种播多久（毫秒）。**必须和 `pets.css` 里那几条 `animation` 的时长一致**——
 * 这个数只用来决定什么时候把类摘掉，短了会在动画中途截断，
 * 长了则是那只已经站定、类还挂着（于是这段时间里它不出列、不干活）。
 */
export const ENTRY_MS: Readonly<Record<EntryKind, number>> = {
  drop: 780,
  chute: 1450,
  splash: 1000,
  fade: 500,
}

/**
 * 这只该怎么登场。
 *
 * 判据先看 `tone` 再看 `shape`：**「没见过的那一家」是个身份，不是个形状**。
 * 它恰好也画成史莱姆，但它和 kimi 那只史莱姆要说的事情正相反——
 * 一个是「这家我认识」，一个是「这家我不认识」，不能共用一套登场。
 */
export function entryOf(look: PetLook): EntryKind {
  if (look.tone === "plain") return "fade"
  if (look.shape === "crab") return "chute"
  if (look.shape === "dsh-mark") return "splash"
  return "drop"
}
