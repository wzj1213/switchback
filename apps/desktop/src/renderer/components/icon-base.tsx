/**
 * 图标。
 *
 * ## 为什么是内联 SVG，不是 emoji、不是字形、不是图标库
 *
 * - **emoji** 是彩色的，和这套单色界面不搭，而且各平台画得不一样。
 * - **字形**（`⌸`、`▾` 之类）在多数字体里会退化成一个含糊的方框。
 * - **图标库**要么进 bundle 几百 KB，要么从 CDN 拉——而这个应用是离线优先的。
 *
 * 内联 SVG 跟着 `currentColor` 走，所以 hover / 选中 / 禁用时颜色自动对，
 * 不用为每种状态各写一份。
 *
 * ## 一套画法
 *
 * 全部 16×16 视口、`stroke-width: 1.3`、圆角端点。混用描边和填充是图标看起来
 * 「不是一套」的最常见原因——所以这里只有描边，唯一的例外是需要表达
 * 「实心状态」的那几个（选中的勾、状态点）。
 *
 * ## 什么才配只剩图标：图形语义自足
 *
 * 判据是**图形语义是否自足**——⧉=复制、齿轮=设置，图形自己就把话说完了，
 * 文字是噪音。反过来，「codex」「gpt-5 高」没有图形可替：选择器（引擎 /
 * 信任档 / 模型）上的文字**就是当前值本身**。同理保留图标+文字的：
 * 审批卡按钮（整个产品最关键的界面，文字必须直白）、右键菜单项
 *（菜单需要文字，图标只是助记）、新建会话主 CTA。别因为「看起来像一套」
 * 就把它们顺手统一成纯图标——统一错了地方，比不一致贵。
 */

export const BOX = { viewBox: "0 0 16 16", fill: "none", "aria-hidden": true } as const

/**
 * 线条属性。**故意不含 `strokeWidth`** —— 那一项由 `Svg` 按尺寸算，见下。
 */
export const LINE = { stroke: "currentColor", strokeLinecap: "round", strokeLinejoin: "round" } as const

/** 渲染出来的笔画粗细（CSS 像素）。整套图标共用这一个数。 */
const STROKE_PX = 1.25

/**
 * 图标外壳。**「多大」和「多重」在这里解耦。**
 *
 * ## 为什么笔画要跟着尺寸反着算
 *
 * 所有图标共用 `viewBox="0 0 16 16"`，笔画原来写死 1.3。而 `width` 是变的
 * （11、12、13、14、15 都有），于是渲染出来的笔画 = `1.3 × size / 16`：
 *
 * | 渲染尺寸 | 实际笔画 |
 * | --- | --- |
 * | 14 | 1.14 |
 * | 12 | 0.98 |
 * | 11 | 0.89 |
 *
 * 侧栏那一列里 14 和 12 是挨着的，**笔画差 28%**——看起来就是有的粗有的细、
 * 边缘有的实有的虚，整列像没对齐。而且 1.14 这种值永远压在像素边界上，
 * 每个图标都糊一点、还糊得不一样。
 *
 * 现在按尺寸反向补偿：`strokeWidth = STROKE_PX × 16 / size`，
 * 于是不管画多大，**落到屏幕上永远是同一个粗细**。
 * 尺寸继续按位置需要挑，重量不再跟着变。
 */
export function Svg({
  size = 14,
  style,
  className,
  children,
}: {
  size?: number
  /** 少数图标要转（展开箭头）。**给它开个口子，而不是让它自己写 `<svg>`**——
      自己写就拿不到上面那套笔画补偿，实测四个图标就是这么漏掉的。 */
  style?: React.CSSProperties
  /** 同一个口子的另一半：**状态和过渡交给 CSS**。写成行内 style 的话，
      `prefers-reduced-motion` 那条媒体查询压根盖不住它。 */
  className?: string
  children: React.ReactNode
}): React.JSX.Element {
  return (
    <svg
      width={size}
      height={size}
      strokeWidth={(STROKE_PX * 16) / size}
      style={style}
      className={className}
      {...BOX}
    >
      {children}
    </svg>
  )
}

/**
 * 侧栏那一列图标的尺寸。
 *
 * **同一条竖线上的东西必须一样大。** 原来这一列里混着 14（新建/打开文件夹/设置）
 * 和 12（项目行的展开箭头），两者上下相邻——一大一小，那列就不成其为一条线了。
 *
 * 段头的箭头例外，它属于另一个层级（小一号字的分节标题），用 `SIDEBAR_ICON_SMALL`。
 */
export const SIDEBAR_ICON = 14
export const SIDEBAR_ICON_SMALL = 12

/**
 * ## 正文区那几档（数字写在各自的调用处，这里说清为什么是这几个）
 *
 * | 档 | 用在哪 | 为什么 |
 * | --- | --- | --- |
 * | **13** | 行内药丸里那颗（复制、改一改再发、从这里重来）、卡头的铅笔 | 和它旁边那行字同高（`--text-sm` 也是 13）。**图标比字小一圈时整颗药丸会显得没做完** |
 * | **14** | 行尾那些 24px 方钮里的（预览、访达、复制这一份） | 方钮 24，图标 14 留 5px 呼吸；再小就成了一个大盒子里的一粒芝麻 |
 * | **15** | 侧栏那一列（`SIDEBAR_ICON`） | 同一条竖线上的东西必须一样大，见上 |
 * | **18** | 灯箱的关闭 | 它压在图片上，周围没有别的东西给它做参照，得自己立得住 |
 *
 * 上一版这里最密集的两档是 **11 和 12**：11 用在行内药丸上（旁边的字 13）、
 * 12 用在 24px 的方钮里。两处都是「图标比该有的小一号」，一屏扫下来
 * 每一颗都显得怯——而这套界面本来就没有多少装饰可以撑场面，图标该有的分量
 * 不能省。整体上抬一档之后，笔画由 `Svg` 自己按尺寸补偿，粗细看起来不变。
 */
