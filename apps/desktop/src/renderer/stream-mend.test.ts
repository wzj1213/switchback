import { describe, expect, it } from "vitest"
import { mendTail } from "./stream-mend.js"

describe("流式期间补上没闭合的行内标记", () => {
  const cases: readonly (readonly [string, string, string])[] = [
    ["粗体还在长", "先说结论：**换会话时要清", "先说结论：**换会话时要清**"],
    ["行内代码还在长", "时间戳要用 `performance.no", "时间戳要用 `performance.no`"],
    ["粗体里套着没收的代码：先收代码再收粗体", "**看 `useFlow", "**看 `useFlow`**"],
    ["收尾只到了一个星号：只补差的那一个", "**换会话时要清滑窗*", "**换会话时要清滑窗**"],
    ["末尾的空白挪到收尾外面，不然收尾不算数", "**换会话时 ", "**换会话时**"],
    ["开头刚到、字还没来：先藏起来，不印一对空的", "结论是 **", "结论是 "],
    ["反引号刚到：同上", "要用 `", "要用 "],
    ["双反引号的代码按一样长的收", "写成 ``a`b", "写成 ``a`b``"],
    ["已经闭合的一概不动", "**粗体** 和 `代码` 都齐了", "**粗体** 和 `代码` 都齐了"],
    ["中文标点夹着的粗体也算闭合", "**原因：**这里要清", "**原因：**这里要清"],
    ["代码里的星号是代码本身", "`a ** b` 然后", "`a ** b` 然后"],
    ["转义的星号不是标记", "\\*\\*不是粗体", "\\*\\*不是粗体"],
    ["前后都是空白的两个星号是乘方，不是开头", "2 ** 10 等于 1024", "2 ** 10 等于 1024"],
    ["单个星号不碰：和列表、乘号撞车", "* 第一项\n* 第二", "* 第一项\n* 第二"],
    ["上一段没闭合的不管：解析器不会跨段", "**上一段\n\n这一段", "**上一段\n\n这一段"],
    ["同一段里跨行的照样补", "- **第一项**：说明\n- **第二", "- **第一项**：说明\n- **第二**"],
    ["停在没闭合的代码围栏里：一个字都不改", "```ts\nconst a = `x", "```ts\nconst a = `x"],
    ["围栏里有空行也还是在围栏里", "```\n**a\n\nb", "```\n**a\n\nb"],
    ["围栏收了，之后那段照常补", "```\ncode\n```\n**粗", "```\ncode\n```\n**粗**"],
    ["波浪线围栏同理", "~~~\n`x\n~~~\n`y", "~~~\n`x\n~~~\n`y`"],
    ["信息串里带反引号的那行不是围栏，是行内代码", "``` a ``` 后面 `b", "``` a ``` 后面 `b`"],
    ["空串", "", ""],
  ]
  for (const [name, input, want] of cases) {
    it(name, () => {
      expect(mendTail(input)).toBe(want)
    })
  }
})
